function requiredInvariants(spec) {
  const base = {
    progress: spec.objective,
  };
  if (spec.profile === "precision") return base;
  base.survival = "对手的可信回复结算后，玩家仍未输且至少保留一条核心引擎或攻击线。";
  base.handoff = "进入第二个玩家回合时存在合法攻击手、能量来源与必要目标访问。";
  if (spec.profile === "composite") {
    base.disruption = "在推进奖赏的同时处理题面公开或可推导的对手终局资源。";
    base.deny_opponent_win = "对手任一枚举回复都不能在下一检查点直接宣告获胜。";
  }
  return base;
}

function buildGraph(deck, spec, index) {
  const puzzleId = `${deck.deckKey}_${String(index + 1).padStart(2, "0")}`;
  const nodes = [
    {
      id: "s0",
      kind: "state",
      label: spec.title,
      fingerprint: spec.start,
      checkpoint: "player_turn_1_main",
    },
    {
      id: "d0",
      kind: "player_decision",
      label: "选择有限资源下的承诺路线",
      operator: "OR",
      axis: "route_choice",
    },
    {
      id: "a_ok",
      kind: "action",
      label: spec.correct,
      actor: "player",
      axis: "route_choice",
      legal_guard: "题面公开资源、卡牌文本、奖差、场位与使用次数均满足。",
      effect_summary: `双用途动作：推进“${spec.objective}”，同时处理公开威胁并保留接力。`,
    },
    {
      id: "g_success",
      kind: "terminal",
      label: "当前进度、对手回应与下一棒同时成立",
      outcome: "success",
      reason: spec.objective,
    },
    {
      id: "t_reply",
      kind: "threat",
      label: "题面可验证的对手回复",
      visibility: spec.threat.visibility,
      evidence: spec.threat.evidence,
      deadline: "对手下一回合结束前",
      impact: spec.threat.impact,
    },
  ];
  const edges = [
    { from: "s0", to: "d0", type: "opens" },
    { from: "d0", to: "a_ok", type: "option" },
    { from: "a_ok", to: "t_reply", type: "counters" },
  ];

  spec.lures.forEach((lure, lureIndex) => {
    const actionId = `a_bad_${lureIndex + 1}`;
    const failId = `f_bad_${lureIndex + 1}`;
    nodes.push(
      {
        id: actionId,
        kind: "action",
        label: lure.label,
        actor: "player",
        axis: lure.axis,
        legal_guard: "动作本身合法且具有局部即时收益。",
        effect_summary: "牺牲了另一项稀缺资源或延迟检查点，因此不是可持续解。",
      },
      {
        id: failId,
        kind: "terminal",
        label: `${lure.axis} 延迟失败`,
        outcome: "failure",
        reason: lure.reason,
        failure_axis: lure.axis,
        consequence_depth: 2,
      }
    );
    edges.push(
      { from: "d0", to: actionId, type: "option" },
      { from: actionId, to: failId, type: "resolves" }
    );
  });

  spec.resources.forEach((resource, resourceIndex) => {
    const id = `r_${resourceIndex + 1}`;
    nodes.push({
      id,
      kind: "resource",
      label: resource.label,
      resource_type: resource.type,
      available: 1,
      minimum_required: 1,
      slack: 0,
      deadline: resource.deadline,
      scarce: true,
    });
    edges.push({ from: "a_ok", to: id, type: "reserves" });
  });

  const invariants = requiredInvariants(spec);
  Object.entries(invariants).forEach(([category, assertion]) => {
    const id = `g_${category}`;
    nodes.push({
      id,
      kind: "invariant",
      label: category,
      category,
      assertion,
    });
    edges.push({ from: "g_success", to: id, type: "requires" });
  });
  edges.push({ from: "a_ok", to: "g_progress", type: "enables" });

  if (spec.profile === "precision") {
    edges.push({ from: "a_ok", to: "g_success", type: "resolves" });
  } else {
    nodes.push(
      {
        id: "s1",
        kind: "state",
        label: "首轮承诺完成，进入对手回应",
        fingerprint: `正确路线已兑现当前进度；仍需覆盖：${spec.threat.evidence}`,
        checkpoint: "opponent_turn_1_start",
      },
      {
        id: "d_reply",
        kind: "opponent_decision",
        label: "覆盖所有题面可信高影响回复",
        operator: "AND",
        credible_set: true,
        coverage_basis: `${spec.threat.evidence}；回复集合来自公开手牌、场上招式或已冻结策略。`,
      }
    );
    edges.push(
      { from: "a_ok", to: "s1", type: "resolves" },
      { from: "s1", to: "d_reply", type: "opens" }
    );
    spec.replies.forEach((reply, replyIndex) => {
      const actionId = `a_reply_${replyIndex + 1}`;
      const stateId = `s2_${replyIndex + 1}`;
      nodes.push(
        {
          id: actionId,
          kind: "action",
          label: reply,
          actor: "opponent",
          axis: "opponent_reply",
          legal_guard: "回复由题面公开资源、场上招式或冻结策略支持。",
          effect_summary: "对当前攻击手、手牌、场地或接力线施压。",
        },
        {
          id: stateId,
          kind: "state",
          label: "回应后仍可接检",
          fingerprint: "玩家未输，目标进度未失效，且保留合法接力攻击与目标访问。",
          checkpoint: "player_turn_2_start",
        }
      );
      edges.push(
        { from: "d_reply", to: actionId, type: "reply" },
        { from: actionId, to: stateId, type: "resolves" },
        { from: stateId, to: "g_success", type: "reaches" }
      );
    });
  }

  return {
    format_version: 1,
    puzzle_id: puzzleId,
    deck_id: deck.deckId,
    revision: 4,
    profile: spec.profile,
    design_status: "review_only_not_wired_to_production",
    title: spec.title,
    objective: spec.objective,
    strategy_id: deck.strategyId,
    start: "s0",
    nodes,
    edges,
    proof: {
      max_depth: 24,
      max_player_turns: 2,
      required_initial_options: spec.profile === "composite" ? 4 : 3,
      opponent_reply_coverage: spec.profile === "precision" ? "not_required" : "all",
      negative_probe_axes: spec.lures.map((lure) => lure.axis),
      claim: "policy_replay_proven",
      uniqueness_scope:
        "枚举的承诺路线等价类；对手回复为设计期AND覆盖，生产期仍需适配器证明。",
    },
  };
}

function writeJson(file, value) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, `${JSON.stringify(value, null, 2)}\n`, "utf8");
}

